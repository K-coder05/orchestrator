"""Codex CLI adapter (``codex exec``), the coding failover agent (§2.8).

Verified against codex-cli 0.163.0 on this Mac (2026-10-21): the flags, the
``-c`` keys (under ``--strict-config``), the ``--json`` event stream
(``tests/fixtures/codex_stream.jsonl`` is a recording), the permission
profile (writes outside the Task folder, reads of home/no-access dirs and
shell network all blocked) and resume by thread id. The usage-limit message
formats still come from the openai/codex source (no real hit observed);
docs/adapters.md says what was checked how.

Shape of an Attempt::

    codex exec --json --skip-git-repo-check --ignore-user-config --ignore-rules \
      --strict-config [-m <model>] -c approval_policy="never" \
      -c default_permissions="nightshift" -c permissions.nightshift.filesystem={...} \
      -c permissions.nightshift.network={enabled=false} -c web_search="disabled" \
      ... -c developer_instructions="<agent protocol>" -          # prompt on stdin

and a resume is the same with ``resume <thread id> -`` at the end.
"""

from __future__ import annotations

import json
import re
import tempfile
from collections.abc import Callable
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from .base import (
    AgentAdapter,
    Command,
    Event,
    EventKind,
    PermissionPolicy,
    Permissions,
    PlanningReply,
    ProbeReply,
    RateLimit,
    TaskContext,
    Usage,
)

#: The per-Task permission profile's name (``default_permissions``).
PROFILE = "nightshift"

#: Item types that are one Step (a tool call). ``agent_message``,
#: ``reasoning``, ``todo_list`` and ``error`` items are not.
STEP_ITEMS = {"command_execution", "file_change", "mcp_tool_call", "web_search", "collab_tool_call"}
#: Item statuses that mean the Step failed.
FAILED_STATUSES = {"failed", "declined"}

# Flags that would switch the sandbox or approvals off, or widen or replace
# the per-Task policy. Nightshift never passes them itself and refuses them in
# agents.codex.extra_args (§1.4). `-c`/`--config` is refused as a whole: any
# override could replace part of the policy.
FORBIDDEN_ARGS = (
    "--dangerously-bypass-approvals-and-sandbox",
    "--yolo",
    "--dangerously-bypass-hook-trust",
    "--sandbox",
    "-s",
    "--full-auto",
    "--approve-for-me",
    "--not-so-yolo",
    "--ask-for-approval",
    "-a",
    "--add-dir",
    "--profile",
    "-p",
    "--config",
    "-c",
    "--cd",
    "-C",
    "--worktree",
    "--oss",
    "--local-provider",
    "--enable",
    "--disable",
    "--search",
    "--remote",
    "--remote-auth-token-env",
    "--cyber-access-program",
)

#: Default-on features (``codex features list``, 0.163.0) that reach outside
#: the shell sandbox (desktop/browser control, ChatGPT apps/connectors,
#: plugins) or that a Task doesn't need: switched off for every run.
DISABLED_FEATURES = (
    "apps",
    "plugins",
    "remote_plugin",
    "browser_use",
    "browser_use_external",
    "in_app_browser",
    "computer_use",
    "image_generation",
    "hooks",
)

PROBE_SYSTEM = "Answer with the single word OK."
PROBE_PROMPT = "OK?"


def _forbidden(args: list[str]) -> list[str]:
    bad = []
    for a in args:
        if any(a == f or a.startswith(f + "=") for f in FORBIDDEN_ARGS):
            bad.append(a)
        elif a.startswith("-c") and len(a) > 2 and not a.startswith("--"):
            bad.append(a)  # -ckey=value
        elif "danger-full-access" in a or "bypass" in a:
            bad.append(a)
    return bad


# --------------------------------------------------------------------------
# TOML values for `-c key=value` (the value part is parsed as TOML)
# --------------------------------------------------------------------------


def toml_value(value: Any) -> str:
    """``value`` as an inline TOML value. Strings use JSON escaping, which is
    valid in TOML basic strings (``\\n``, ``\\"``, ``\\uXXXX``)."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(str(k))} = {toml_value(v)}"
                               for k, v in value.items()) + "}"
    raise TypeError(f"no TOML form for {type(value).__name__}")


def config_args(overrides: dict[str, Any]) -> list[str]:
    """``-c key=value`` pairs, in order."""
    out: list[str] = []
    for key, value in overrides.items():
        out += ["-c", f"{key}={toml_value(value)}"]
    return out


def toml_document(overrides: dict[str, Any]) -> str:
    """The same overrides as a config.toml document (an audit copy only:
    Codex gets them through ``-c``)."""
    lines = ["# Generated by Nightshift for one Task; passed to `codex exec` as -c overrides.",
             "# Codex does not read this file (docs/adapters.md)."]
    for key, value in overrides.items():
        lines.append(f"{key} = {toml_value(value)}")
    return "\n".join(lines) + "\n"


class CodexAdapter(AgentAdapter):
    name = "codex"
    #: Codex takes over Claude's work (§2.8), so it runs in Claude's lane:
    #: never beside a Claude Task (§5 item 5).
    lane = "claude"

    def __init__(self, settings: dict[str, Any] | None = None):
        settings = settings or {}
        self.binary: str = settings.get("binary") or "codex"
        self.model: str | None = settings.get("model")
        self.planning_model: str | None = settings.get("planning_model") or self.model
        # `model_reasoning_effort` (low|medium|high|...); None = the model's default.
        self.reasoning_effort: str | None = settings.get("reasoning_effort")
        # On a resume: the session total the earlier Attempts ended at (the
        # runner sets it), since `turn.completed` reports the thread's total.
        self.prior_usage: dict[str, Any] | None = None
        self.extra_args: list[str] = list(settings.get("extra_args") or [])
        self._session_id: str | None = None
        self._usage: dict[str, Any] | None = None  # the last turn.completed usage
        self._completed = False
        self._failed: str | None = None  # turn.failed message
        self._errors: list[str] = []  # `error` events
        self._last_message: str | None = None
        self._started: set[str] = set()  # Step item ids already counted
        self._turns = 0
        self.clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc)

    # -- invocation ----------------------------------------------------------
    def _flags(self, *, ephemeral: bool = False) -> list[str]:
        argv = [self.binary, "exec", "--json", "--skip-git-repo-check",
                "--ignore-user-config", "--ignore-rules", "--strict-config"]
        if ephemeral:
            argv.append("--ephemeral")
        return argv

    def _model_args(self, model: str | None) -> list[str]:
        argv = ["-m", model] if model else []
        if self.reasoning_effort:
            argv += config_args({"model_reasoning_effort": self.reasoning_effort})
        return argv

    def _task_argv(self, permissions: Permissions, task: TaskContext | None) -> list[str]:
        overrides = permissions.sandbox.get("overrides") if permissions.sandbox else None
        if permissions.settings_file is None or not overrides:
            raise ValueError("refusing to start Codex without a per-Task permission policy")
        if (overrides.get("approval_policy") != "never"
                or "danger-full-access" in json.dumps(overrides)):
            raise ValueError("Codex runs only sandboxed with approvals off (§1.4)")
        bad = _forbidden(self.extra_args)
        if bad:
            raise ValueError(f"agents.codex.extra_args may not contain {bad} (§1.4)")
        argv = self._flags()
        argv += self._model_args(self.model)
        argv += config_args(overrides)
        if task is not None:
            argv += config_args({"developer_instructions": task.protocol})
        return argv + self.extra_args

    def build_command(
        self, task: TaskContext, workspace: Path, permissions: Permissions
    ) -> Command:
        # `-`: the whole prompt comes from stdin (not in argv, never read as a flag).
        return Command(argv=self._task_argv(permissions, task) + ["-"], stdin=task.prompt)

    def resume_command(
        self,
        session_id: str,
        prompt: str,
        *,
        task: TaskContext | None = None,
        permissions: Permissions | None = None,
    ) -> Command:
        if permissions is None:
            raise ValueError("a resumed Attempt needs the Task's permissions too")
        argv = self._task_argv(permissions, task) + ["resume", session_id, "-"]
        return Command(argv=argv, stdin=prompt)

    def _toolless_overrides(self, system: str) -> dict[str, Any]:
        """A session with no shell (``features.shell_tool = false``), a
        read-only sandbox, no network, no web search, no hooks."""
        return {
            "approval_policy": "never",
            "default_permissions": ":read-only",
            "features.shell_tool": False,
            **_disabled_features(),
            "web_search": "disabled",
            "check_for_update_on_startup": False,
            "history.persistence": "none",
            "developer_instructions": system,
        }

    def planning_command(self, prompt: str, *, system: str, schema: dict[str, Any]) -> Command:
        """``codex exec --ephemeral`` with no shell, read-only, and
        ``--output-schema`` for the JSON answer (the last agent message)."""
        fd, path = tempfile.mkstemp(prefix="nightshift-codex-schema-", suffix=".json")
        with open(fd, "w") as f:
            json.dump(strict_schema(schema), f)
        argv = self._flags(ephemeral=True) + self._model_args(self.planning_model)
        argv += config_args(self._toolless_overrides(system))
        argv += ["--output-schema", path, "-"]
        return Command(argv=argv, stdin=prompt)

    def probe_command(self) -> Command:
        """The smallest request: no shell, no session saved, a one-word
        answer. Uses the Task model (``agents.codex.model``)."""
        argv = self._flags(ephemeral=True) + self._model_args(self.model)
        argv += config_args(self._toolless_overrides(PROBE_SYSTEM)) + ["-"]
        return Command(argv=argv, stdin=PROBE_PROMPT)

    def write_permissions(self, workspace: Path, policy: PermissionPolicy) -> Permissions:
        """Codex settings for one Task as ``-c`` overrides: a custom permission
        profile (filesystem read/write/deny per path, no network), approvals
        off (anything that would need one is refused), web search only on
        internet-on Tasks, no hooks, a minimal shell environment with
        ``TMPDIR`` inside the Task folder. See docs/safety.md. Writes an audit
        copy to ``<settings_dir>/codex-config.toml``."""
        if policy.settings_dir is None:
            raise ValueError("PermissionPolicy.settings_dir is required")
        ws = str(policy.workspace)
        fs: dict[str, Any] = {":root": "read", ":minimal": "read"}
        # Private roots (home, agents_root) unreadable; more specific entries
        # below re-allow what the Task may see.
        for p in policy.private_roots:
            fs[str(p)] = "deny"
        for p in policy.tool_dirs:
            fs[str(p)] = "read"
        read_only = [d for d in policy.read_only_dirs if d.is_dir()]
        for p in policy.read_only_dirs:
            fs[str(p)] = "read"
        for p in policy.no_access_dirs:
            fs[str(p)] = "deny"  # deny wins over read/write on the same path
        fs[":workspace_roots"] = {".": "write"}
        fs[ws] = "write"
        overrides: dict[str, Any] = {
            "approval_policy": "never",
            "default_permissions": PROFILE,
            f"permissions.{PROFILE}.filesystem": fs,
            # Shell commands get no network on any Task (§1.4).
            f"permissions.{PROFILE}.network": {"enabled": False},
            "web_search": "live" if policy.internet else "disabled",
            **_disabled_features(),
            "check_for_update_on_startup": False,
            "history.persistence": "none",
            "shell_environment_policy.inherit": "core",
            "shell_environment_policy.ignore_default_excludes": False,
            "shell_environment_policy.set": {"TMPDIR": str(policy.workspace / ".tmp")},
        }
        (policy.workspace / ".tmp").mkdir(parents=True, exist_ok=True)
        policy.settings_dir.mkdir(parents=True, exist_ok=True)
        settings_file = policy.settings_dir / "codex-config.toml"
        settings_file.write_text(toml_document(overrides))
        deny = [p for p, v in fs.items() if v == "deny"]
        return Permissions(
            tools=["shell", "apply_patch"] + (["web_search"] if policy.internet else []),
            allow=[],
            deny=deny,
            read_only_dirs=read_only,
            sandbox={"overrides": overrides},
            settings_file=settings_file,
            permission_mode="approval_policy=never",
        )

    # -- stream ----------------------------------------------------------------
    def parse_stream(self, line: str) -> list[Event]:
        line = line.strip()
        if not line:
            return []
        try:
            msg = json.loads(line)
        except json.JSONDecodeError:
            return [Event(EventKind.TEXT, {"text": line, "raw": True})]
        if not isinstance(msg, dict):
            return [Event(EventKind.OTHER, {"value": msg})]
        mtype = msg.get("type")
        if mtype == "thread.started":
            if msg.get("thread_id") and not self._session_id:
                self._session_id = str(msg["thread_id"])
            return [Event(EventKind.SESSION, {"session_id": msg.get("thread_id")})]
        if mtype == "turn.started":
            self._turns += 1
            return [Event(EventKind.OTHER, {"type": mtype})]
        if mtype == "turn.completed":
            self._completed = True
            if isinstance(msg.get("usage"), dict):
                self._usage = msg["usage"]
            return [
                Event(EventKind.USAGE, {"usage": msg.get("usage"), "final": True}),
                Event(EventKind.RESULT, {"is_error": False, "text": self._last_message}),
            ]
        if mtype == "turn.failed":
            err = msg.get("error") or {}
            text = str(err.get("message") if isinstance(err, dict) else err or "turn failed")
            self._failed = text
            return [
                Event(EventKind.ERROR, {"message": text}),
                Event(EventKind.RESULT, {"is_error": True, "text": text}),
            ]
        if mtype == "error":
            text = str(msg.get("message") or "")
            if _RETRYING.match(text):
                # The CLI retries on its own ("Reconnecting... 2/5"): not fatal.
                return [Event(EventKind.OTHER, {"type": "retrying", "message": text})]
            self._errors.append(text)
            return [Event(EventKind.ERROR, {"message": text})]
        if mtype in ("item.started", "item.updated", "item.completed"):
            return self._item_events(mtype, msg.get("item") or {})
        return [Event(EventKind.OTHER, {"type": mtype})]

    def _item_events(self, mtype: str, item: dict[str, Any]) -> list[Event]:
        itype = item.get("type")
        iid = str(item.get("id") or "")
        events: list[Event] = []
        if itype in STEP_ITEMS:
            if iid not in self._started and mtype in ("item.started", "item.completed"):
                self._started.add(iid)
                events.append(Event(EventKind.TOOL_CALL, {
                    "id": iid, "name": itype, "input": _step_input(item)}))
            if mtype == "item.completed":
                failed = item.get("status") in FAILED_STATUSES or bool(item.get("error"))
                events.append(Event(EventKind.TOOL_RESULT, {"tool_use_id": iid, "is_error": failed}))
                if itype == "file_change" and not failed:
                    for ch in item.get("changes") or []:
                        if isinstance(ch, dict):
                            events.append(Event(EventKind.FILE_CHANGE, {
                                "path": ch.get("path"), "tool": "apply_patch",
                                "kind": ch.get("kind")}))
                if failed:
                    events.append(Event(EventKind.ERROR, {
                        "tool_use_id": iid, "tool_error": True,
                        "message": str(item.get("error") or item.get("aggregated_output")
                                       or item.get("status"))[:500]}))
            return events
        if mtype != "item.completed":
            return [Event(EventKind.OTHER, {"type": itype, "status": "in_progress"})]
        if itype == "agent_message":
            self._last_message = item.get("text")
            return [Event(EventKind.TEXT, {"text": item.get("text") or ""})]
        if itype == "error":
            # A warning item (config warnings, deprecation notices); never fatal.
            return [Event(EventKind.OTHER, {"type": "warning", "message": item.get("message")})]
        return [Event(EventKind.OTHER, {"type": itype})]

    # -- results -------------------------------------------------------------
    def detect_rate_limit(self, event_or_exit: Event | int) -> RateLimit | None:
        """A usage-limit hit: an agent error (``error`` event or
        ``turn.failed``, never a tool's output) whose message is one of the
        CLI's usage-limit texts (docs/adapters.md, from
        ``codex-rs/protocol/src/error.rs``): "You've hit your usage limit
        ... Try again at 3:20 PM." / "... at Apr 30th, 2026 11:21 AM.",
        "Quota exceeded", a 429 / "rate limit exceeded". The reset time is
        read from the text (Mac local time); the CLI never names the
        Window. The exit code alone says nothing."""
        if not isinstance(event_or_exit, Event):
            return None
        ev = event_or_exit
        if ev.kind != EventKind.ERROR or ev.data.get("tool_error"):
            return None
        text = str(ev.data.get("message") or "")
        if not _LIMIT_TEXT.search(text):
            return None
        return RateLimit(limit_type=None, reset_at=parse_reset_text(text, self.clock()))

    def session_id(self) -> str | None:
        return self._session_id

    def usage_from_run(self) -> list[Usage]:
        """From the last ``turn.completed``: ``input_tokens`` includes the
        cached ones, so input = input - cached; cache read = cached; cache
        write = ``cache_write_input_tokens``; output includes reasoning
        tokens. Codex reports no cost (``cost_usd`` None). An Attempt stopped
        before ``turn.completed`` has no usage line at all.

        ``turn.completed`` carries the **thread's** running total (verified on
        a real resume), so a resumed Attempt subtracts ``prior_usage`` (the
        total its session ended at before). ``raw`` keeps the total as reported."""
        if not self._usage:
            return []
        u = self._usage
        prior = self.prior_usage or {}

        def part(key: str) -> int:
            return max(int(u.get(key) or 0) - int(prior.get(key) or 0), 0)

        inp = part("input_tokens")
        cached = part("cached_input_tokens")
        return [Usage(
            model=self.model,
            input_tokens=max(inp - cached, 0),
            output_tokens=part("output_tokens"),
            cache_creation_tokens=part("cache_write_input_tokens"),
            cache_read_tokens=cached,
            requests=self._turns or None,
            cost_usd=None,
            raw=dict(u),
        )]

    def result_ok(self) -> bool | None:
        if self._failed is not None:
            return False
        if self._completed:
            return True
        return False if self._errors else None

    def result_error(self) -> str | None:
        if self.result_ok() is not False:
            return None
        return self._failed or (self._errors[-1] if self._errors else None)

    # -- planning and probes -----------------------------------------------
    def _replay(self, stdout: str) -> tuple["CodexAdapter", RateLimit | None]:
        probe = CodexAdapter({"model": self.model})
        probe.clock = self.clock
        limit = None
        for line in stdout.splitlines():
            for ev in probe.parse_stream(line):
                hit = probe.detect_rate_limit(ev)
                if hit is not None and (limit is None or (limit.reset_at is None and hit.reset_at)):
                    limit = hit
        return probe, limit

    def parse_planning_output(self, stdout: str, exit_code: int) -> PlanningReply:
        run, limit = self._replay(stdout)
        usage = run.usage_from_run()
        if exit_code != 0 or not run.result_ok():
            err = run.result_error() or f"no result from codex (exit code {exit_code})"
            return PlanningReply(ok=False, error=err, text=run._last_message, usage=usage)
        text = run._last_message or ""
        try:
            structured = json.loads(text)
        except json.JSONDecodeError:
            structured = None
        if not isinstance(structured, dict):
            return PlanningReply(ok=False, error="codex did not return a JSON answer",
                                 text=text, usage=usage)
        return PlanningReply(ok=True, structured=structured, text=text, usage=usage)

    def parse_probe_output(self, stdout: str, exit_code: int) -> ProbeReply:
        run, limit = self._replay(stdout)
        usage = run.usage_from_run()
        if limit is not None:
            return ProbeReply(available=False, limit=limit, usage=usage)
        if exit_code == 0 and run.result_ok():
            return ProbeReply(available=True, usage=usage)
        err = run.result_error() or f"no result from codex (exit code {exit_code})"
        return ProbeReply(available=False, error=err, usage=usage)


def _disabled_features() -> dict[str, bool]:
    return {f"features.{f}": False for f in DISABLED_FEATURES}


def _step_input(item: dict[str, Any]) -> dict[str, Any]:
    keys = ("command", "changes", "server", "tool", "arguments", "query")
    return {k: item[k] for k in keys if k in item}


def strict_schema(schema: dict[str, Any]) -> dict[str, Any]:
    """OpenAI structured outputs (``--output-schema``) want every property
    required and no extra properties, at every object level."""
    out = dict(schema)
    if out.get("type") == "object" and isinstance(out.get("properties"), dict):
        out["properties"] = {k: strict_schema(v) if isinstance(v, dict) else v
                             for k, v in out["properties"].items()}
        out["required"] = list(out["properties"])
        out["additionalProperties"] = False
    return out


_RETRYING = re.compile(r"\s*(Reconnecting|Re-connecting|Retrying)\b", re.IGNORECASE)
_LIMIT_TEXT = re.compile(
    r"hit your usage limit|usage limit|quota exceeded|rate limit exceeded|too many requests"
    r"|\b429\b|out of credits|spend cap",
    re.IGNORECASE,
)
_MONTHS = "jan feb mar apr may jun jul aug sep oct nov dec".split()
_AT_TEXT = re.compile(
    r"try again at\s+"
    r"(?:(?P<mon>Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\.?\s+(?P<day>\d{1,2})"
    r"(?:st|nd|rd|th)?,?\s+(?P<year>\d{4})\s+)?"
    r"(?P<h>\d{1,2}):(?P<m>\d{2})\s*(?P<ap>AM|PM)",
    re.IGNORECASE,
)
_IN_TEXT = re.compile(
    r"try again in\s+(?:(?P<d>\d+)\s*days?\s*)?(?:(?P<h>\d+)\s*hours?\s*)?"
    r"(?:(?P<m>\d+)\s*min(?:ute)?s?)?",
    re.IGNORECASE,
)


def parse_reset_text(text: str, now: datetime) -> str | None:
    """The reset time in a Codex usage-limit message, as ISO 8601, or None.

    Codex formats it in the Mac's local zone: ``Try again at 3:20 PM.`` (the
    same day), ``Try again at Apr 30th, 2026 11:21 AM.`` (another day). Older
    CLIs said ``Try again in 1 day 23 hours 37 minutes.`` A same-day clock
    time already passed is taken as tomorrow."""
    if not text:
        return None
    local_now = now.astimezone()
    m = _AT_TEXT.search(text)
    if m:
        hour = int(m.group("h")) % 12 + (12 if m.group("ap").upper() == "PM" else 0)
        minute = int(m.group("m"))
        if hour > 23 or minute > 59:
            return None
        try:
            if m.group("mon"):
                at = local_now.replace(year=int(m.group("year")),
                                       month=_MONTHS.index(m.group("mon")[:3].lower()) + 1,
                                       day=int(m.group("day")), hour=hour, minute=minute,
                                       second=0, microsecond=0)
            else:
                at = local_now.replace(hour=hour, minute=minute, second=0, microsecond=0)
                if at <= local_now:
                    at += timedelta(days=1)
        except ValueError:
            return None
        return at.isoformat(timespec="seconds")
    m = _IN_TEXT.search(text)
    if m and any(m.group(k) for k in ("d", "h", "m")):
        delta = timedelta(days=int(m.group("d") or 0), hours=int(m.group("h") or 0),
                          minutes=int(m.group("m") or 0))
        return (local_now + delta).isoformat(timespec="seconds")
    return None
