"""The agent adapter interface (§2.9).

Core code only talks to ``AgentAdapter``. An adapter instance is created per
Attempt, so it can accumulate what it learns from the output stream (session
id, usage) and report it through ``session_id()`` and ``usage_from_run()``.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path
from typing import Any


class EventKind(StrEnum):
    TEXT = "text"
    TOOL_CALL = "tool_call"  # one Step
    FILE_CHANGE = "file_change"
    USAGE = "usage"
    ERROR = "error"
    SESSION = "session"  # the agent announced its session id
    RATE_LIMIT_INFO = "rate_limit_info"  # window status, not necessarily a hit
    RESULT = "result"  # final result of the session
    OTHER = "other"


@dataclass
class Event:
    kind: EventKind
    data: dict[str, Any] = field(default_factory=dict)


@dataclass
class Permissions:
    """Per-Task tool policy handed to ``build_command``.

    Generated by ``write_permissions``; issue #4 extends this with the full
    §1.4/§1.6 policy.
    """

    allowed_tools: list[str] = field(default_factory=list)
    disallowed_tools: list[str] = field(default_factory=list)
    read_only_dirs: list[Path] = field(default_factory=list)
    permission_mode: str = "acceptEdits"


@dataclass
class TaskContext:
    """What an adapter needs to know about the Task it runs."""

    id: str
    prompt: str
    task_type: str
    internet: str
    protocol: str  # the §2.10 agent protocol text, injected into every Attempt


@dataclass
class Command:
    argv: list[str]
    stdin: str | None = None
    env: dict[str, str] = field(default_factory=dict)  # extra env vars


@dataclass
class RateLimit:
    limit_type: str | None
    reset_at: str | None  # ISO 8601, if the agent reported one


@dataclass
class Usage:
    """Usage for one model within one Attempt; every field the agent reports."""

    model: str | None
    input_tokens: int | None = None
    output_tokens: int | None = None
    cache_creation_tokens: int | None = None
    cache_read_tokens: int | None = None
    requests: int | None = None
    cost_usd: float | None = None  # reported cost-equivalent
    raw: dict[str, Any] | None = None

    def as_dict(self) -> dict[str, Any]:
        return self.__dict__.copy()


class AgentAdapter(ABC):
    name: str

    @abstractmethod
    def build_command(
        self, task: TaskContext, workspace: Path, permissions: Permissions
    ) -> Command:
        """The headless invocation for a fresh session."""

    @abstractmethod
    def parse_stream(self, line: str) -> list[Event]:
        """Normalize one line of agent output into events."""

    @abstractmethod
    def detect_rate_limit(self, event_or_exit: Event | int) -> RateLimit | None:
        """Return the limit type and reset time if this is a rate-limit hit."""

    @abstractmethod
    def session_id(self) -> str | None:
        """The session id seen so far in this Attempt."""

    @abstractmethod
    def resume_command(
        self,
        session_id: str,
        prompt: str,
        *,
        task: TaskContext | None = None,
        permissions: Permissions | None = None,
    ) -> Command:
        """The invocation that resumes ``session_id`` with ``prompt``.

        When ``task`` is given its protocol is injected again: every Attempt,
        resumes included, carries the agent protocol.
        """

    @abstractmethod
    def usage_from_run(self) -> list[Usage]:
        """Tokens/requests and reported cost for this Attempt, per model."""

    @abstractmethod
    def write_permissions(self, workspace: Path, policy: dict[str, Any]) -> Permissions:
        """Generate the per-Task allowlist, deny rules and read-only dirs."""

    def result_ok(self) -> bool | None:
        """Whether the agent reported success (None if it never reported)."""
        return None

    def result_error(self) -> str | None:
        return None
