#: Tools that write a file (path in ``file_path``): a ``file_change`` on success.
WRITE_TOOLS = {"write_file", "replace"}
#: The built-in tools of every Task (``tools.core``: no other tool exists).
TASK_TOOLS = ["read_file", "read_many_files", "write_file", "replace",
              "glob", "grep_search", "list_directory", "run_shell_command"]
#: Added on internet-on Tasks. Both run in the CLI process, not the shell sandbox.
WEB_TOOLS = ["web_fetch", "google_web_search"]
#: An MCP server name nobody uses: with it as the only allowed name, none start.
NO_MCP = "nightshift-none"

# Flags that would switch approvals or the sandbox off, widen the workspace,
# load other policies/extensions, or take over the prompt or session.
# Nightshift never passes them itself and refuses them in
# agents.gemini.extra_args (§1.4).
FORBIDDEN_ARGS = (
    "--yolo", "-y", "--approval-mode", "--sandbox", "-s", "--policy", "--admin-policy",
    "--include-directories", "--allowed-tools", "--allowed-mcp-server-names",
    "--extensions", "-e", "--skip-trust", "--worktree", "-w", "--resume", "-r",
    "--session-id", "--session-file", "--delete-session", "--acp", "--experimental-acp",
    "--prompt", "-p", "--prompt-interactive", "-i", "--output-format", "-o",
    "--raw-output", "--accept-raw-output-risk", "--fake-responses",
    "--fake-responses-non-strict", "--record-responses",
)

#: ``security.auth.selectedType`` values Nightshift supports.
AUTH_API_KEY = "gemini-api-key"  # an AI Studio API key (GEMINI_API_KEY)
AUTH_GOOGLE = "oauth-personal"  # Sign in with Google (the AI Pro plan)
AUTH_TYPES = (AUTH_API_KEY, AUTH_GOOGLE)
#: Minutes without output, a Step in flight and no command running, after
#: which an Attempt counts as stalled (the 0.65.0 sandbox-expansion hang).
DEFAULT_STALL_MINUTES = 5.0

PROBE_SYSTEM = "Answer with the single word OK."
PROBE_PROMPT = "OK?"


def _forbidden(args: list[str]) -> list[str]:
    return [a for a in args if any(a == f or a.startswith(f + "=") for f in FORBIDDEN_ARGS)
            or "yolo" in a]


def js_escape(text: str) -> str:
    """``text`` as a literal inside a JavaScript regex (the policy engine
    compiles ``argsPattern``/``commandRegex`` with ``new RegExp``)."""
    return re.sub(r"[.*+?^${}()|\[\]\\/]", lambda m: "\\" + m.group(0), text)


def _anycase(text: str) -> str:
    """A case-insensitive JS regex for ``text`` without flags (JS has no
    inline ``(?i)`` on every Node the CLI supports)."""
    return "".join(f"[{c.lower()}{c.upper()}]" if c.isalpha() else js_escape(c) for c in text)


def policy_document(rules: list[dict[str, Any]]) -> str:
    lines = ["# Generated by Nightshift for one Task; loaded with --admin-policy (admin tier:",
             "# beats user and workspace policies). Regenerated every Attempt."]
    for rule in rules:
        lines.append("\n[[rule]]")
        lines += [f"{k} = {toml_value(v)}" for k, v in rule.items()]
    return "\n".join(lines) + "\n"


def safe_path(path: str, private_roots: list[Path], tool_dirs: list[Path]) -> str:
    """``PATH`` for Gemini. Its shell sandbox lets every command read each
    ``PATH`` entry (the parent of a ``.../bin`` entry), so an entry like
    ``~/bin`` would open all of ``~``. Kept: entries outside the private
    roots (home, agents_root) whose readable folder doesn't contain one, and
    entries inside ``permissions.tool_dirs``."""
    def inside(p: Path, root: Path) -> bool:
        return p == root or root in p.parents

    out: list[str] = []
    for entry in path.split(":"):
        if not entry.startswith("/") or entry in out:
            continue
        real = Path(os.path.realpath(entry))
        readable = real.parent if real.name == "bin" else real
        if any(inside(root, readable) for root in private_roots):
            continue  # it would expose a whole private root
        if any(inside(real, root) for root in private_roots) and not any(
                inside(readable, t) or inside(real, t) for t in tool_dirs):
            continue
        out.append(entry)
    return ":".join(out)


def link_system_bins(path: str, private_roots: list[Path], dest: Path) -> bool:
    """Links to the programs of ``PATH`` entries that ``safe_path`` drops
    although they hold no private data: ``/bin`` and ``/sbin``, whose
    readable folder would be ``/``. Without them the shell sandbox can't
    even start ``bash``; through links in ``dest`` it reads only ``dest``
    (the programs themselves are readable in Gemini's base profile).
    Returns whether ``dest`` should go on ``PATH``."""
    def inside(p: Path, root: Path) -> bool:
        return p == root or root in p.parents

    found = False
    for entry in path.split(":"):
        if not entry.startswith("/"):
            continue
        real = Path(os.path.realpath(entry))
        readable = real.parent if real.name == "bin" else real
        if not (real.is_dir() and any(inside(r, readable) for r in private_roots)
                and not any(inside(real, r) for r in private_roots)):
            continue
        dest.mkdir(parents=True, exist_ok=True)
        found = True
        for prog in real.iterdir():
            link = dest / prog.name
            if not link.is_symlink() and not link.exists() and os.access(prog, os.X_OK):
                link.symlink_to(prog)
    return found


class GeminiAdapter(AgentAdapter):
    name = "gemini"
    #: The Gemini lane (§5 item 5), the paid API path's too.
    lane = "gemini"

    def __init__(self, settings: dict[str, Any] | None = None):
        settings = settings or {}
        self.binary: str = settings.get("binary") or "gemini"
        self.model: str | None = settings.get("model")
        self.planning_model: str | None = settings.get("planning_model") or self.model
        self.extra_args: list[str] = list(settings.get("extra_args") or [])
        self.auth_type: str = str(settings.get("auth") or AUTH_API_KEY)
        if self.auth_type not in AUTH_TYPES:
            raise ValueError(f"agents.{self.name}.auth must be one of {list(AUTH_TYPES)}, "
                             f"not {self.auth_type!r}")
        # The runner (and planning calls, probes) set ``api_key`` from this secret.
        self.api_key_secret = ((settings.get("api_key_secret") or "GEMINI_API_KEY")
                               if self.auth_type == AUTH_API_KEY else None)
        stall = settings.get("stall_minutes", DEFAULT_STALL_MINUTES)
        self.stall_seconds = float(stall) * 60 if stall else None
        self._session_id: str | None = None
        self._model_seen: str | None = None
        self._stats: dict[str, Any] | None = None  # the result line's stats
        self._status: str | None = None  # result status: success | error
        self._error: str | None = None  # result error message
        self._errors: list[str] = []  # `error` events with severity error
        self._text: list[str] = []  # assistant deltas since the last tool call
        self._all_text: list[str] = []  # every assistant delta
        self._pending: dict[str, dict[str, Any]] = {}  # tool_id -> tool_use line
        self.clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc)
        # Where the user's Gemini config is checked (~/.gemini); tests move it.
        self.home: Path = Path.home()

    # -- invocation ----------------------------------------------------------
    def _base_argv(self, model: str | None, policy_file: Path) -> list[str]:
        argv = [self.binary, "--output-format", "stream-json", "--approval-mode", "default",
                "--admin-policy", str(policy_file), "-e", "none",
                "--allowed-mcp-server-names", NO_MCP]
        return argv + (["-m", model] if model else [])

    def _env(self, cli_home: Path, tmpdir: Path | None, tool_dirs: list[Path],
             private_roots: list[Path]) -> dict[str, str]:
        env = {
            # The CLI's home: its user settings layer is Nightshift's file,
            # your ~/.gemini settings, policies, extensions and sessions are
            # not read (a system settings file would be skipped unless every
            # folder above it is owned by root, seen on 0.65.0).
            "GEMINI_CLI_HOME": str(cli_home),
            # The folder is never trusted: its .gemini/settings.json never loads
            # (headless runs anyway: security.folderTrust.enabled is false).
            "GEMINI_CLI_TRUST_WORKSPACE": "false",
            # No whole-CLI container/Seatbelt relaunch; shell commands are
            # sandboxed one by one (security.toolSandboxing).
            "GEMINI_SANDBOX": "false",
            "PATH": safe_path(os.environ.get("PATH", ""), private_roots, tool_dirs),
            # Only Nightshift's key, never one from your shell: GOOGLE_API_KEY
            # would win over GEMINI_API_KEY, and on Google sign-in no key is
            # passed at all. The CLI treats an empty value as unset.
            "GEMINI_API_KEY": self._key(),
            "GOOGLE_API_KEY": "",
        }
        if tmpdir is not None:
            env["TMPDIR"] = str(tmpdir)
        sysbin = cli_home / "sysbin"
        if link_system_bins(os.environ.get("PATH", ""), private_roots, sysbin):
            env["PATH"] = ":".join(p for p in (env["PATH"], str(sysbin)) if p)
        return env

    def _task_command(self, permissions: Permissions, extra: list[str], stdin: str) -> Command:
        sb = permissions.sandbox or {}
        if permissions.settings_file is None or not sb.get("policy_file") or not sb.get("tmpdir"):
            raise ValueError("refusing to start Gemini without a per-Task permission policy")
        bad = _forbidden(self.extra_args)
        if bad:
            raise ValueError(f"agents.gemini.extra_args may not contain {bad} (§1.4)")
        argv = self._base_argv(self.model, Path(sb["policy_file"]))
        for d in permissions.read_only_dirs:
            argv += ["--include-directories", str(d)]
        env = self._env(Path(sb["cli_home"]), Path(sb["tmpdir"]),
                        [Path(p) for p in sb.get("tool_dirs") or []],
                        [Path(p) for p in sb.get("private_roots") or []])
        return Command(argv=argv + extra + self.extra_args, stdin=stdin, env=env)

    def _key(self) -> str:
        if self.auth_type != AUTH_API_KEY:
            return ""
        if not self.api_key:
            raise ValueError(f"agents.{self.name} signs in with an API key: put "
                             f"{self.api_key_secret} in .env or the Keychain")
        return self.api_key

    @staticmethod
    def _with_protocol(task: TaskContext | None, prompt: str) -> str:
        # Gemini has no "append to the system prompt" flag: the protocol goes
        # in front of the prompt, on every Attempt.
        return f"{task.protocol}\n\n---\n\n{prompt}" if task is not None else prompt

    def build_command(
        self, task: TaskContext, workspace: Path, permissions: Permissions
    ) -> Command:
        return self._task_command(permissions, [], self._with_protocol(task, task.prompt))

    def resume_command(
        self,
        session_id: str,
        prompt: str,
        *,
        task: TaskContext | None = None,
        permissions: Permissions | None = None,
    ) -> Command:
        if permissions is None:
            raise ValueError("a resumed Attempt needs the Task's permissions too")
        return self._task_command(permissions, ["--resume", session_id],
                                  self._with_protocol(task, prompt))

    def _settings(self, tools: list[str]) -> dict[str, Any]:
        return {
            "security": {
                "auth": {"selectedType": self.auth_type},
                "toolSandboxing": True,
                # Off, so a headless run in the (untrusted) Task folder starts;
                # GEMINI_CLI_TRUST_WORKSPACE=false still marks it untrusted.
                "folderTrust": {"enabled": False},
                "disableYoloMode": True,
                "disableAlwaysAllow": True,
                "enablePermanentToolApproval": False,
                "autoAddToPolicyByDefault": False,
                "environmentVariableRedaction": {"enabled": True},
            },
            "tools": {
                "core": tools,
                "sandbox": False,
                "sandboxNetworkAccess": False,
                "discoveryCommand": "",
                "callCommand": "",
                "shell": {"enableInteractiveShell": False},
            },
            "mcp": {"serverCommand": ""},
            "hooksConfig": {"enabled": False},
            "skills": {"enabled": False},
            "experimental": {"enableAgents": False, "worktrees": False,
                             "extensionReloading": False},
            "general": {
                "checkpointing": {"enabled": False},
                "enableAutoUpdate": False,
                "enableAutoUpdateNotification": False,
                "defaultApprovalMode": "default",
            },
            "ide": {"enabled": False},
        }

    def _user_config_problems(self) -> list[str]:
        """User config Nightshift can't switch off: ``~/.gemini/policies/sandbox.toml``
        (persistent shell-sandbox grants and mode network settings). It is
        read from the real home even under GEMINI_CLI_HOME
        (SandboxPolicyManager uses os.homedir())."""
        sandbox_toml = self.home / ".gemini" / "policies" / "sandbox.toml"
        return [f"{sandbox_toml} exists"] if sandbox_toml.exists() else []

    #: Sign-in files linked from your ~/.gemini into each CLI home.
    SIGN_IN_FILES = ("oauth_creds.json", "google_accounts.json")

    def _cli_home(self, home: Path, tools: list[str]) -> Path:
        """A GEMINI_CLI_HOME: ``.gemini/settings.json`` (Nightshift's
        settings as the user layer) and links to your sign-in files. Kept
        between Attempts (the Task's sessions live in ``.gemini/tmp``);
        the settings are rewritten each time. Returns the settings file."""
        gem = home / ".gemini"
        gem.mkdir(parents=True, exist_ok=True, mode=0o700)
        for name in self.SIGN_IN_FILES:
            src, link = self.home / ".gemini" / name, gem / name
            if self.auth_type != AUTH_GOOGLE:
                link.unlink(missing_ok=True)  # an API key needs no Google sign-in
            elif src.exists() and not link.exists():
                link.unlink(missing_ok=True)  # a dangling link
                link.symlink_to(src)
        settings_file = gem / "settings.json"
        settings_file.write_text(json.dumps(self._settings(tools), indent=2) + "\n")
        return settings_file

    def write_permissions(self, workspace: Path, policy: PermissionPolicy) -> Permissions:
        """Gemini settings for one Task: a system-layer settings file (tool
        allowlist, per-command shell sandbox with no network, no hooks,
        skills, subagents, extensions or MCP servers) and an admin-tier
        policy file (deny everything but the Task tools; deny writes to
        read-only folders, shell commands naming them, and web fetches of
        denied domains). Both live in ``<settings_dir>``, which the agent
        can't reach. See docs/safety.md."""
        if policy.settings_dir is None:
            raise ValueError("PermissionPolicy.settings_dir is required")
        problems = self._user_config_problems()
        if problems:
            raise ValueError("refusing to start Gemini: " + "; ".join(problems)
                             + " (it would widen the Task's access, docs/safety.md)")
        tools = TASK_TOOLS + (WEB_TOOLS if policy.internet else [])
        read_only = [d for d in policy.read_only_dirs if d.is_dir()]
        rules: list[dict[str, Any]] = [
            {"toolName": "*", "decision": "deny", "priority": 0,
             "denyMessage": "Not available in Nightshift Tasks."},
            # allowRedirection: else `>`/`2>&1` turn the allow into "ask",
            # i.e. deny headless (seen on 0.65.0). Writes stay sandboxed.
            {"toolName": tools, "decision": "allow", "priority": 500, "allowRedirection": True},
            # A relative path climbing out of the Task folder could land in a
            # read-only folder (it is in the workspace): no `..` in write paths.
            {"toolName": sorted(WRITE_TOOLS), "decision": "deny", "priority": 900,
             "argsPattern": r'"file_path":"[^"]*\.\.',
             "denyMessage": "Write paths may not contain '..'."},
        ]
        home = str(self.home)
        for d in policy.read_only_dirs + policy.no_access_dirs:
            forms = [js_escape(str(d))]
            if str(d).startswith(home + "/"):
                rel = js_escape(str(d)[len(home) + 1:])
                forms += [f"~/{rel}", f"\\$HOME/{rel}", f"\\$\\{{HOME\\}}/{rel}"]
            alt = "(?:" + "|".join(forms) + ")"
            rules.append({"toolName": sorted(WRITE_TOOLS), "decision": "deny", "priority": 900,
                          "argsPattern": f'"file_path":"{alt}(?:/|")',
                          "denyMessage": f"{d} is read-only or off limits."})
            # `.*`, not "any char but an unescaped quote": the CLI drops rules
            # with a group followed by a quantifier (its ReDoS check, seen on
            # 0.65.0). It may also match the description; that only denies more.
            rules.append({"toolName": "run_shell_command", "decision": "deny", "priority": 900,
                          "commandRegex": ".*" + alt,
                          "denyMessage": f"Shell commands may not touch {d}; use read_file."})
        if policy.internet and policy.denied_domains:
            alt = "|".join(_anycase(dom) for dom in policy.denied_domains)
            rules.append({"toolName": WEB_TOOLS, "decision": "deny", "priority": 900,
                          "argsPattern": f"(?:{alt})",
                          "denyMessage": "That domain is never fetched (§1.6)."})
        tmpdir = policy.workspace / ".tmp"
        tmpdir.mkdir(parents=True, exist_ok=True)
        policy.settings_dir.mkdir(parents=True, exist_ok=True)
        cli_home = policy.settings_dir / "gemini-home"
        settings_file = self._cli_home(cli_home, tools)
        policy_file = policy.settings_dir / "gemini-policy.toml"
        policy_file.write_text(policy_document(rules))
        return Permissions(
            tools=tools,
            allow=list(tools),
            deny=[r.get("argsPattern") or r.get("commandRegex") or "*" for r in rules
                  if r["decision"] == "deny"],
            read_only_dirs=read_only,
            sandbox={"policy_file": str(policy_file), "tmpdir": str(tmpdir),
                     "cli_home": str(cli_home),
                     "tool_dirs": [str(p) for p in policy.tool_dirs],
                     "private_roots": [str(p) for p in policy.private_roots]},
            settings_file=settings_file,
            permission_mode="approval-mode=default (headless: anything not allowed is denied)",
        )

    def _toolless_command(self, model: str | None, stdin: str) -> Command:
        """No tools at all (``tools.core`` empty, every call denied by
        policy), no hooks, skills, extensions or MCP servers. There is no
        Task (so no settings_dir): the files go to a private temp folder,
        rewritten each call (their content never changes)."""
        d = Path(tempfile.gettempdir()) / f"nightshift-gemini-{os.getuid()}"
        d.mkdir(mode=0o700, exist_ok=True)
        self._cli_home(d / "home", [])
        policy_file = d / "toolless-policy.toml"
        policy_file.write_text(policy_document([
            {"toolName": "*", "decision": "deny", "priority": 0,
             "denyMessage": "No tools in planning calls and probes."}]))
        argv = self._base_argv(model, policy_file)
        env = self._env(d / "home", None, [], [])
        # No tools means no shell, so PATH needs no filtering; filtering it
        # (as for a Task, without tool_dirs) would drop an nvm-installed
        # `gemini` and its `node` (seen on the real CLI).
        env["PATH"] = os.environ.get("PATH", "")
        return Command(argv=argv, stdin=stdin, env=env)

    def planning_command(self, prompt: str, *, system: str, schema: dict[str, Any]) -> Command:
        """A tool-less one-shot call. Gemini has no JSON-schema flag, so the
        schema goes in the prompt and the answer is the reply text, parsed
        as JSON (``parse_planning_output``)."""
        stdin = (f"{system}\n\nReply with one JSON object and nothing else (no code "
                 f"fences), matching this JSON Schema:\n{json.dumps(schema)}\n\n---\n\n{prompt}")
        return self._toolless_command(self.planning_model, stdin)

    def probe_command(self) -> Command:
        """The smallest request: no tools, a one-word answer. Uses the Task
        model (``agents.gemini.model``), since Gemini quotas are per model."""
        return self._toolless_command(self.model, f"{PROBE_SYSTEM}\n\n{PROBE_PROMPT}")

    # -- stream ----------------------------------------------------------------
    def parse_stream(self, line: str) -> list[Event]:
        line = line.strip()
        if not line:
            return []
        try:
            msg = json.loads(line)
        except json.JSONDecodeError:
            return [Event(EventKind.TEXT, {"text": line, "raw": True})]
        if not isinstance(msg, dict):
            return [Event(EventKind.OTHER, {"value": msg})]
        mtype = msg.get("type")
        if mtype == "init":
            if msg.get("session_id") and not self._session_id:
                self._session_id = str(msg["session_id"])
            self._model_seen = msg.get("model") or self._model_seen
            return [Event(EventKind.SESSION, {"session_id": msg.get("session_id"),
                                              "model": msg.get("model")})]
        if mtype == "message":
            if msg.get("role") != "assistant":
                return [Event(EventKind.OTHER, {"type": "message", "role": msg.get("role")})]
            text = str(msg.get("content") or "")
            self._text.append(text)
            self._all_text.append(text)
            return [Event(EventKind.TEXT, {"text": text})]
        if mtype == "tool_use":
            tid = str(msg.get("tool_id") or "")
            self._pending[tid] = msg
            self._text = []
            return [Event(EventKind.TOOL_CALL, {
                "id": tid, "name": msg.get("tool_name"), "input": msg.get("parameters") or {}})]
        if mtype == "tool_result":
            return self._tool_result(msg)
        if mtype == "error":
            text = str(msg.get("message") or "")
            if msg.get("severity") != "error":
                # Loop detection, blocked-by-hook notices, retries: not fatal.
                return [Event(EventKind.OTHER, {"type": "warning", "message": text})]
            self._errors.append(text)
            return [Event(EventKind.ERROR, {"message": text})]
        if mtype == "result":
            return self._result(msg)
        return [Event(EventKind.OTHER, {"type": mtype})]

    def _tool_result(self, msg: dict[str, Any]) -> list[Event]:
        tid = str(msg.get("tool_id") or "")
        use = self._pending.pop(tid, {})
        failed = msg.get("status") == "error"
        events = [Event(EventKind.TOOL_RESULT, {"tool_use_id": tid, "is_error": failed})]
        if failed:
            err = msg.get("error") or {}
            events.append(Event(EventKind.ERROR, {
                "tool_use_id": tid, "tool_error": True,
                "error_type": err.get("type") if isinstance(err, dict) else None,
                "message": str(err.get("message") if isinstance(err, dict) else err)[:500]}))
        elif use.get("tool_name") in WRITE_TOOLS:
            path = (use.get("parameters") or {}).get("file_path")
            if path:
                events.append(Event(EventKind.FILE_CHANGE, {"path": path, "tool": use["tool_name"]}))
        return events

    def _result(self, msg: dict[str, Any]) -> list[Event]:
        self._status = str(msg.get("status") or "")
        if isinstance(msg.get("stats"), dict):
            self._stats = msg["stats"]
        events = [Event(EventKind.USAGE, {"usage": msg.get("stats"), "final": True})]
        if self._status == "error":
            err = msg.get("error") or {}
            etype = err.get("type") if isinstance(err, dict) else None
            text = str((err.get("message") if isinstance(err, dict) else err) or "gemini failed")
            self._error = text
            events.append(Event(EventKind.ERROR, {"message": text, "error_type": etype}))
            events.append(Event(EventKind.RESULT, {"is_error": True, "text": text}))
        else:
            events.append(Event(EventKind.RESULT, {"is_error": False,
                                                   "text": "".join(self._text) or None}))
        return events

    # -- results -------------------------------------------------------------
    def detect_rate_limit(self, event_or_exit: Event | int) -> RateLimit | None:
        """A quota hit: an agent error (never a tool's) whose text says a
        quota or capacity is exhausted, or that ends in the CLI's 429 note
        ("Possible quota limitations in place..."), or that the CLI typed
        ``TerminalQuotaError``. An API error during a turn reaches the
        ``result`` line as ``error.type: "unknown"`` (seen on 0.65.0: the
        turn passes a plain {message, status}), so the text is what counts;
        ``RetryableQuotaError`` is excluded when it is typed. The reset time comes from the
        text ("Please retry in 34s", "Suggested retry after 3600s", "reset
        after 2h31m10s"); a daily quota with none is probed. The exit code
        alone says nothing."""
        if not isinstance(event_or_exit, Event):
            return None
        ev = event_or_exit
        if ev.kind != EventKind.ERROR or ev.data.get("tool_error"):
            return None
        text = str(ev.data.get("message") or "")
        etype = ev.data.get("error_type")
        if etype == "RetryableQuotaError" or (etype != "TerminalQuotaError"
                                              and not _LIMIT_TEXT.search(text)):
            return None
        limits = [int(n) for n in _QUOTA_LIMIT.findall(text)]
        if limits and not any(limits):
            # "limit: 0": the model has no quota on this key's tier at all
            # (seen: a pro model on a free-tier key). Waiting won't help, so
            # this is a failure to fix in config, not a Window running out.
            return None
        window = "daily" if re.search(r"\bdaily\b|PerDay", text, re.IGNORECASE) else None
        return RateLimit(limit_type=window, reset_at=parse_reset_text(text, self.clock()))

    def session_id(self) -> str | None:
        return self._session_id

    def usage_from_run(self) -> list[Usage]:
        """One ``Usage`` per model from the ``result`` line's ``stats.models``:
        ``input_tokens`` there includes the cached prompt tokens, so input =
        ``input`` (the uncached part), cache read = ``cached``, output =
        ``output_tokens``. No cost and no request count are reported. An
        Attempt stopped before its ``result`` line has no usage."""
        if not self._stats:
            return []
        models = self._stats.get("models") or {}
        if not models and self._stats.get("total_tokens"):
            models = {self._model_seen or self.model or "unknown": self._stats}
        out = []
        for name, m in models.items():
            # The CLI lists every model it touched, e.g. the "auto" router's
            # with all zeros when its call failed (seen on 0.65.0).
            if not isinstance(m, dict) or not any(m.get(k) for k in (
                    "total_tokens", "input_tokens", "output_tokens", "cached", "input")):
                continue
            prompt = int(m.get("input_tokens") or 0)
            cached = int(m.get("cached") or 0)
            uncached = m.get("input")
            out.append(Usage(
                model=name,
                input_tokens=int(uncached) if uncached is not None else max(prompt - cached, 0),
                output_tokens=int(m.get("output_tokens") or 0),
                cache_creation_tokens=None,
                cache_read_tokens=cached,
                requests=None,
                cost_usd=None,
                raw=dict(m),
            ))
        return out

    def result_ok(self) -> bool | None:
        if self._status == "success":
            return True
        if self._status == "error":
            return False
        return False if self._errors else None

    def result_error(self) -> str | None:
        if self.result_ok() is not False:
            return None
        return self._error or (self._errors[-1] if self._errors else None)

    # -- planning and probes -----------------------------------------------
    def _replay(self, stdout: str) -> tuple["GeminiAdapter", RateLimit | None]:
        run = GeminiAdapter({"model": self.model, "auth": self.auth_type})
        run.clock = self.clock
        limit = None
        for line in stdout.splitlines():
            for ev in run.parse_stream(line):
                hit = run.detect_rate_limit(ev)
                if hit is not None and (limit is None or (limit.reset_at is None and hit.reset_at)):
                    limit = hit
        return run, limit

    def parse_planning_output(self, stdout: str, exit_code: int) -> PlanningReply:
        run, _ = self._replay(stdout)
        usage = run.usage_from_run()
        text = "".join(run._all_text).strip()
        if exit_code != 0 or not run.result_ok():
            err = run.result_error() or f"no result from gemini (exit code {exit_code})"
            return PlanningReply(ok=False, error=err, text=text or None, usage=usage)
        fenced = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", text, re.DOTALL)
        try:
            structured = json.loads(fenced.group(1) if fenced else text)
        except json.JSONDecodeError:
            structured = None
        if not isinstance(structured, dict):
            return PlanningReply(ok=False, error="gemini did not return a JSON answer",
                                 text=text, usage=usage)
        return PlanningReply(ok=True, structured=structured, text=text, usage=usage)

    def parse_probe_output(self, stdout: str, exit_code: int) -> ProbeReply:
        run, limit = self._replay(stdout)
        usage = run.usage_from_run()
        if limit is not None:
            return ProbeReply(available=False, limit=limit, usage=usage)
        if exit_code == 0 and run.result_ok():
            return ProbeReply(available=True, usage=usage)
        err = run.result_error() or f"no result from gemini (exit code {exit_code})"
        return ProbeReply(available=False, error=err, usage=usage)


class GeminiApiAdapter(GeminiAdapter):
    """The paid Gemini API path (AI Studio credits, §1.5): the same CLI and
    per-Task settings, signed in with an API key (``security.auth.selectedType``
    ``gemini-api-key``, the key in ``GEMINI_API_KEY``, from the secret
    ``GEMINI_PAID_API_KEY``).

    Every model call is read from the CLI's local telemetry file
    (``GEMINI_TELEMETRY_OUTFILE``, in the Nightshift-owned settings folder):
    one ``gemini_cli.api_response`` log record per call, with its token
    counts. ``paid_calls()`` returns the calls written since the last call.
    No planning calls or probes run here (they would spend), and quota or
    credit errors are not usage-Window hits: there is no plan to wait for.
    """

    name = "gemini-api"
    paid = True
    subscription = "gemini"
    TELEMETRY_FILE = "gemini-api-calls.json"

    def __init__(self, settings: dict[str, Any] | None = None):
        settings = settings or {}
        # A billed project's key, never the free-tier key of agents.gemini.
        super().__init__({**settings, "auth": AUTH_API_KEY, "api_key_secret":
                          settings.get("api_key_secret") or "GEMINI_PAID_API_KEY"})
        self._telemetry: Path | None = None
        self._telemetry_pos = 0
        self._telemetry_buf = ""

    def _task_command(self, permissions: Permissions, extra: list[str], stdin: str) -> Command:
        command = super()._task_command(permissions, extra, stdin)
        self._telemetry = Path(permissions.sandbox["telemetry_file"])
        command.env |= {
            # Telemetry to a local file only (an outfile turns OTLP export off),
            # without prompts. Env beats every settings layer.
            "GEMINI_TELEMETRY_ENABLED": "true",
            "GEMINI_TELEMETRY_TARGET": "local",
            "GEMINI_TELEMETRY_OUTFILE": str(self._telemetry),
            "GEMINI_TELEMETRY_LOG_PROMPTS": "false",
            "GEMINI_TELEMETRY_USE_COLLECTOR": "false",
        }
        return command

    def write_permissions(self, workspace: Path, policy: PermissionPolicy) -> Permissions:
        permissions = super().write_permissions(workspace, policy)
        assert policy.settings_dir is not None
        telemetry = policy.settings_dir / self.TELEMETRY_FILE
        telemetry.unlink(missing_ok=True)  # one file per Attempt
        permissions.sandbox["telemetry_file"] = str(telemetry)
        return permissions

    def paid_calls(self) -> list[PaidCall]:
        """Model calls written to the telemetry file since the last call.
        The CLI writes whole records (pretty-printed JSON, spans and metrics
        in between); a record still being written waits for the next call."""
        if self._telemetry is None or not self._telemetry.exists():
            return []
        with open(self._telemetry, encoding="utf-8", errors="replace") as f:
            f.seek(self._telemetry_pos)
            self._telemetry_buf += f.read()
            self._telemetry_pos = f.tell()
        calls, decoder, buf = [], json.JSONDecoder(), self._telemetry_buf
        while True:
            buf = buf.lstrip()
            if not buf:
                break
            try:
                record, end = decoder.raw_decode(buf)
            except json.JSONDecodeError:
                if buf.startswith("{") and buf.find("\n{", 1) == -1:
                    break  # a record still being written
                nxt = buf.find("{", 1)  # not a record: skip to the next one
                if nxt == -1:
                    break
                buf = buf[nxt:]
                continue
            buf = buf[end:]
            attrs = record.get("attributes") if isinstance(record, dict) else None
            if not isinstance(attrs, dict) or attrs.get("event.name") != "gemini_cli.api_response":
                continue
            calls.append(PaidCall(
                model=attrs.get("model"),
                prompt_tokens=int(attrs.get("input_token_count") or 0),
                cached_tokens=int(attrs.get("cached_content_token_count") or 0),
                output_tokens=int(attrs.get("output_token_count") or 0),
                thoughts_tokens=int(attrs.get("thoughts_token_count") or 0),
                tool_prompt_tokens=int(attrs.get("tool_token_count") or 0),
                raw={k: v for k, v in attrs.items() if k.endswith("_count") or k in (
                    "model", "event.timestamp", "prompt_id", "auth_type", "status_code")},
            ))
        self._telemetry_buf = buf
        return calls

    def detect_rate_limit(self, event_or_exit: Event | int) -> RateLimit | None:
        return None

    def planning_command(self, prompt: str, *, system: str, schema: dict[str, Any]) -> Command:
        raise ValueError("the paid Gemini API path is not used for planning calls")

    def probe_command(self) -> Command:
        raise ValueError("the paid Gemini API path has no usage Window to probe")


_LIMIT_TEXT = re.compile(
    r"exhausted your (?:daily )?quota|exhausted your capacity|capacity exceeded"
    r"|MODEL_CAPACITY_EXHAUSTED|QUOTA_EXHAUSTED|quota exceeded|usage limit reached"
    # The Gemini API's 429 on an API key (seen 2026-10-23: "You exceeded your
    # current quota, ... * Quota exceeded for metric: ..., limit: N, model: M").
    r"|exceeded your current quota"
    # The CLI's own suffixes on an HTTP 429: under Google sign-in, and on an
    # API key ("Please wait and try again later. To increase your limits, ...").
    r"|Possible quota limitations in place|To increase your limits, request a quota increase",
    re.IGNORECASE,
)
#: The "limit: N" of each quota the Gemini API says was exceeded.
_QUOTA_LIMIT = re.compile(r"Quota exceeded for metric: [^\n]*?, limit: (\d+)", re.IGNORECASE)
_RETRY_IN = re.compile(r"(?:retry in|retry after|reset after|resets? in)\s+"
                       r"(?:(?P<h>\d+)h\s*)?(?:(?P<m>\d+)m(?!s)\s*)?(?:(?P<s>[\d.]+)(?P<unit>ms|s))?",
                       re.IGNORECASE)


def parse_reset_text(text: str, now: datetime) -> str | None:
    """The reset time in a Gemini quota message, as ISO 8601, or None:
    "Please retry in 34.5s" / "500ms" (the Google API's text), "Suggested
    retry after 3600s." (the CLI's, from RetryInfo), "reset after 2h31m10s"."""
    m = _RETRY_IN.search(text or "")
    if not m or not any(m.group(k) for k in ("h", "m", "s")):
        return None
    seconds = float(m.group("s") or 0) / (1000 if m.group("unit") == "ms" else 1)
    delta = timedelta(hours=int(m.group("h") or 0), minutes=int(m.group("m") or 0), seconds=seconds)
    return (now.astimezone() + delta).replace(microsecond=0).isoformat(timespec="seconds")
