"""The agent adapter interface (§2.9).

Core code only talks to ``AgentAdapter``. An adapter instance is created per
Attempt, so it can accumulate what it learns from the output stream (session
id, usage) and report it through ``session_id()`` and ``usage_from_run()``.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path
from typing import Any


class EventKind(StrEnum):
    TEXT = "text"
    TOOL_CALL = "tool_call"  # one Step
    TOOL_RESULT = "tool_result"  # a Step finished (data: tool_use_id, is_error)
    FILE_CHANGE = "file_change"
    USAGE = "usage"
    ERROR = "error"
    SESSION = "session"  # the agent announced its session id
    RATE_LIMIT_INFO = "rate_limit_info"  # window status, not necessarily a hit
    RESULT = "result"  # final result of the session
    OTHER = "other"


@dataclass
class Event:
    kind: EventKind
    data: dict[str, Any] = field(default_factory=dict)


@dataclass
class PermissionPolicy:
    """The agent-agnostic access policy for one Task (§1.4, §1.6).

    Built by ``nightshift.permissions.build_policy`` from config and the
    Task; each adapter turns it into its own agent's settings with
    ``write_permissions``. All paths are absolute and resolved.
    """

    workspace: Path  # the Task folder: the only writable place
    internet: bool
    read_only_dirs: list[Path] = field(default_factory=list)  # read, never write
    no_access_dirs: list[Path] = field(default_factory=list)  # never read or write
    # Roots whose contents are unreadable to shell commands except for the
    # workspace, the read-only dirs and ``tool_dirs`` (home and agents_root).
    private_roots: list[Path] = field(default_factory=list)
    tool_dirs: list[Path] = field(default_factory=list)  # readable to shell commands only
    denied_domains: list[str] = field(default_factory=list)  # web fetch never goes here
    denied_commands: list[str] = field(default_factory=list)  # shell deny-list (best effort)
    settings_dir: Path | None = None  # Nightshift-owned, agent-inaccessible place for settings files


@dataclass
class Permissions:
    """Per-Task agent settings handed to ``build_command``/``resume_command``.

    Generated by ``write_permissions`` from a ``PermissionPolicy``. Adapters
    refuse to build a command from a ``Permissions`` that carries no policy.
    """

    tools: list[str] = field(default_factory=list)  # the only tools that exist in the session
    allow: list[str] = field(default_factory=list)  # allow rules
    deny: list[str] = field(default_factory=list)  # deny rules (win over allow)
    read_only_dirs: list[Path] = field(default_factory=list)  # existing dirs added read-only
    sandbox: dict[str, Any] = field(default_factory=dict)  # agent sandbox settings
    settings_file: Path | None = None  # where the generated settings were written
    permission_mode: str = "acceptEdits"


@dataclass
class TaskContext:
    """What an adapter needs to know about the Task it runs."""

    id: str
    prompt: str
    task_type: str
    internet: str
    protocol: str  # the §2.10 agent protocol text, injected into every Attempt


@dataclass
class Command:
    argv: list[str]
    stdin: str | None = None
    env: dict[str, str] = field(default_factory=dict)  # extra env vars


@dataclass
class RateLimit:
    limit_type: str | None
    reset_at: str | None  # ISO 8601, if the agent reported one


@dataclass
class WindowInfo:
    """What the agent said about one of its usage Windows (not a hit).

    Claude reports this on every ``rate_limit_event``; Nightshift keeps the
    latest per agent and Window to know where the current Window starts.
    """

    window: str  # e.g. five_hour, seven_day
    resets_at: str | None = None  # ISO 8601
    utilization: float | None = None  # 0..1 of the whole plan, interactive use included
    status: str | None = None


@dataclass
class Usage:
    """Usage for one model within one Attempt; every field the agent reports."""

    model: str | None
    input_tokens: int | None = None
    output_tokens: int | None = None
    cache_creation_tokens: int | None = None
    cache_read_tokens: int | None = None
    requests: int | None = None
    cost_usd: float | None = None  # reported cost-equivalent
    raw: dict[str, Any] | None = None

    def as_dict(self) -> dict[str, Any]:
        return self.__dict__.copy()


@dataclass
class PlanningReply:
    """What a planning call returned (§2.4): no tools, one answer, no session."""

    ok: bool
    structured: dict[str, Any] | None = None  # the answer, validated against the schema
    text: str | None = None
    error: str | None = None
    usage: list[Usage] = field(default_factory=list)


@dataclass
class ProbeReply:
    """What a minimal probe request found out about an agent's usage (§1.5).

    ``available``: the request went through, the Window has reset.
    ``limit``: it was refused by a usage limit (reset time if reported).
    Neither: the probe itself failed (``error``) and says nothing.
    """

    available: bool
    limit: RateLimit | None = None
    error: str | None = None
    usage: list[Usage] = field(default_factory=list)
    windows: list[WindowInfo] = field(default_factory=list)


class AgentAdapter(ABC):
    name: str

    @abstractmethod
    def build_command(
        self, task: TaskContext, workspace: Path, permissions: Permissions
    ) -> Command:
        """The headless invocation for a fresh session."""

    @abstractmethod
    def parse_stream(self, line: str) -> list[Event]:
        """Normalize one line of agent output into events."""

    @abstractmethod
    def detect_rate_limit(self, event_or_exit: Event | int) -> RateLimit | None:
        """Return the limit type and reset time if this is a rate-limit hit."""

    @abstractmethod
    def session_id(self) -> str | None:
        """The session id seen so far in this Attempt."""

    @abstractmethod
    def resume_command(
        self,
        session_id: str,
        prompt: str,
        *,
        task: TaskContext | None = None,
        permissions: Permissions | None = None,
    ) -> Command:
        """The invocation that resumes ``session_id`` with ``prompt``.

        When ``task`` is given its protocol is injected again: every Attempt,
        resumes included, carries the agent protocol.
        """

    @abstractmethod
    def usage_from_run(self) -> list[Usage]:
        """Tokens/requests and reported cost for this Attempt, per model."""

    @abstractmethod
    def write_permissions(self, workspace: Path, policy: PermissionPolicy) -> Permissions:
        """Generate the per-Task allowlist, deny rules, sandbox settings and
        added read-only dirs, writing any settings file the agent needs."""

    @abstractmethod
    def planning_command(self, prompt: str, *, system: str, schema: dict[str, Any]) -> Command:
        """A quick one-shot call with no tools that answers ``prompt`` as JSON
        matching ``schema`` (used for free-form estimates and plans, §2.4).
        It must not give the agent any file, shell or web access."""

    @abstractmethod
    def parse_planning_output(self, stdout: str, exit_code: int) -> PlanningReply:
        """Turn a planning call's output into a ``PlanningReply``."""

    @abstractmethod
    def probe_command(self) -> Command:
        """The smallest request that tells whether the agent's usage Window
        has reset: no tools, no session, a one-word answer (§1.5)."""

    @abstractmethod
    def parse_probe_output(self, stdout: str, exit_code: int) -> ProbeReply:
        """Turn a probe's output into a ``ProbeReply``."""

    def window_info(self, event: Event) -> list[WindowInfo]:
        """Usage-Window status carried by ``event`` (none by default)."""
        return []

    def result_ok(self) -> bool | None:
        """Whether the agent reported success (None if it never reported)."""
        return None

    def result_error(self) -> str | None:
        return None
